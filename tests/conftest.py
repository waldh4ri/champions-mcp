"""Shared pytest fixtures for the test suite.

Provides the session-scoped `db` fixture that the other test modules rely on
to query the built champions.sqlite mirror, skipping data-dependent tests
when that database has not been pulled yet.
"""

from __future__ import annotations

import os
from pathlib import Path

import pytest

from champions_mcp.db import Db

_DB_PATH = Path(__file__).resolve().parents[1] / "data" / "champions.sqlite"


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item, call):
    """CHAMPIONS_MCP_STRICT_TESTS=1 (set in CI): a skip is a failure.

    Locally, tests skip when the database, the simulator image or the MCP SDK
    isn't there. In CI all of them are provided, so a skip means something
    that should exist didn't, and must not pass silently."""
    outcome = yield
    report = outcome.get_result()
    if os.environ.get("CHAMPIONS_MCP_STRICT_TESTS") == "1" and report.skipped:
        report.outcome = "failed"
        report.longrepr = f"skipped in strict mode: {report.longrepr}"


@pytest.fixture(scope="session")
def db() -> Db:
    """Open the local champions.sqlite mirror for the whole test session.

    Skips the requesting test (rather than failing) when the database file
    has not been built yet, since it is generated by a separate pull step.

    Returns:
        Db: a handle to the champions.sqlite mirror, shared by every test
            that declares this fixture.
    """
    if not _DB_PATH.exists():
        pytest.skip(
            f"{_DB_PATH} not built — run `champions-mcp-pull` before the data tests."
        )
    return Db(_DB_PATH)
